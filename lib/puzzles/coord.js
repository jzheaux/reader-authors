/**
 * The fence's text: the grid's width and height, the points, a stroke to a
 * line, and how many have been plotted (all of them, for an answer key).
 */
export function board(picture, plotted = 0) {
  const [w, h] = picture.size;
  const lines = [`grid: ${w} x ${h}`];
  for (const stroke of picture.lines) lines.push(stroke.map(([x, y]) => `(${x}, ${y})`).join(' '));
  lines.push(`plotted: ${plotted === true ? points(picture) : plotted}`);
  return lines.join('\n');
}

/** How many points there are to plot. */
export function points(picture) {
  return picture.lines.reduce((n, stroke) => n + stroke.length, 0);
}
